//! rekordbox 7.2.19's keyboard commands: id, name, category and the keys its presets give them.
//!
//! Read from the thirteen `getCommandInfo` functions of the binary by running each with every
//! command id under each preset (scripts and raw result in `checks/ui-compare/prefs/trace/`).
//! A command that repeats per deck, mixer channel or FX unit is listed once: `scope` 1 repeats
//! it for decks 1 to 4 (id + 0x100 per deck; the keys are those of deck 1 and deck 2, deck 3 has
//! none and deck 4 the same as deck 2, as in rekordbox), 2 for mixer channels 1 to 4 ("CHn "
//! before the name), 3 for FX1 and FX2. The Export preset is the mapping rekordbox itself writes
//! (`rekordbox_0000000000030.mappings`); its second player is the first with Shift.
//! Generated by gen_keys.py; do not edit by hand.

